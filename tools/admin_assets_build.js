#!/usr/bin/env node
/* Bundle Cubby's own fonts into the admin Worker, which has no [assets] directory (spec §4.1: no byte is
 * served before the Access check, so the Worker serves its fonts itself, from a module it imports).
 *
 *   node tools/admin_assets_build.js           write workers/admin/src/fonts.gen.mjs from app/fonts
 *   node tools/admin_assets_build.js --check   exit 1 if the committed module differs from app/fonts
 *
 * The app's Fraunces and Nunito Sans are variable fonts: every weight file of one family and subset is the
 * same bytes, so one file per family and subset covers every weight. test/admin-access.test.js also
 * compares the bytes the Worker SERVES with app/fonts, so the module cannot drift unseen.
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'workers', 'admin', 'src', 'fonts.gen.mjs');
const FILES = {
  'fraunces-latin.woff2': 'fraunces-400-latin.woff2',
  'fraunces-latin-ext.woff2': 'fraunces-400-latin-ext.woff2',
  'nunitosans-latin.woff2': 'nunitosans-400-latin.woff2',
  'nunitosans-latin-ext.woff2': 'nunitosans-400-latin-ext.woff2',
};

function build() {
  const lines = ['/* GENERATED by tools/admin_assets_build.js from app/fonts. Do not edit by hand. */', 'export const FONTS = {'];
  for (const [name, src] of Object.entries(FILES)) {
    const b64 = fs.readFileSync(path.join(ROOT, 'app', 'fonts', src)).toString('base64');
    lines.push('  ' + JSON.stringify(name) + ': ' + JSON.stringify(b64) + ',');
  }
  lines.push('};', '');
  return lines.join('\n');
}

const want = build();
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== want) { console.log('FAIL workers/admin/src/fonts.gen.mjs differs from app/fonts: run node tools/admin_assets_build.js'); process.exit(1); }
  console.log('ADMIN-ASSETS: PASS (fonts.gen.mjs equals app/fonts)');
} else {
  fs.writeFileSync(OUT, want);
  console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + Math.round(want.length / 1024) + ' KB)');
}
module.exports = { FILES };
