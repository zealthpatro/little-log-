#!/usr/bin/env python3
"""Build the native launch splash: the painted Cubby face, centred on Cubby cream.

WHY THIS EXISTS
`npx cap add ios` ships Capacitor's own splash (a blue X on white) in Splash.imageset, and builds 1-5
carried it: every launch flashed Capacitor branding before the cream app appeared. The splash should be
the bear on Cubby cream (#F7F2E8), matching `ios.backgroundColor` and the app's own background so launch
reads as one continuous surface.

The source is the founder's master, icons/icon-master-1024.png (2026-11-13): the painted hero cub's face
on a honey ground, the same image every icon is resized from (tools/gen_brand_icons.py). Until then this
script flood-filled the FLAT Pillow-drawn face out of icons/logo-512.png; that face is gone everywhere.

A splash is not an icon: we want the face alone on flat cream, not a pasted-on honey tile (its edge would
draw a visible square against #F7F2E8). So:
  1. Honey = the mean of the master's 40px border band (its paper is very even, std ~2-3 per channel).
  2. Segment the face as "everything NOT reachable from the corners through honey-like pixels" (flood
     fill), so the cream muzzle, pink ears and cheeks, all enclosed by the face, stay in.
  3. Pull a soft matte on the outer fringe only (colour difference from honey), and un-mix the honey
     out of those pixels, so the fur's edge sits on cream with no yellow halo.
  4. Lanczos-resize so the face's long side is ~22% of the canvas, well inside what survives
     aspect-fill cropping on every device, at the optical centre (46% height); flatten to RGB.

`ios/` and `android/` are gitignored and regenerated by `npx cap add`, so the output is NOT durable:
re-run after any regen (tools/cap_ios_build.sh does). All three iOS imageset scales get the same 2732
universal image, which is what Capacitor's stock Contents.json expects. With an android/ folder present
the Android splash drawables get the same face at each density and orientation.

Usage: python3 tools/gen_splash.py                 write into ios/ (and android/) of this tree
       python3 tools/gen_splash.py --out DIR       write the same tree under DIR instead
"""
import argparse
import os
import sys
from collections import deque

import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MASTER = os.path.join(ROOT, 'icons', 'icon-master-1024.png')
IOS_DIR = os.path.join('ios', 'App', 'App', 'Assets.xcassets', 'Splash.imageset')
IOS_NAMES = ['splash-2732x2732.png', 'splash-2732x2732-1.png', 'splash-2732x2732-2.png']
ANDROID_RES = os.path.join('android', 'app', 'src', 'main', 'res')
ANDROID = [('drawable', 480, 320)] + [
    ('drawable-%s-%s' % (o, d), *(wh if o == 'port' else wh[::-1]))
    for o in ('port', 'land')
    for d, wh in (('mdpi', (320, 480)), ('hdpi', (480, 800)), ('xhdpi', (720, 1280)), ('xxhdpi', (960, 1600)), ('xxxhdpi', (1280, 1920)))
]
CANVAS = 2732
CREAM = (0xF7, 0xF2, 0xE8)
FACE_FRAC = 0.22      # face long side as a fraction of the canvas's short side
CENTRE_Y = 0.46       # optical centre, slightly above geometric
BG_THRESH = 18        # max per-channel distance from honey that still counts as background


def cut_face():
    if not os.path.exists(MASTER):
        sys.exit('No master at %s' % MASTER)
    img = Image.open(MASTER).convert('RGB')
    a = np.asarray(img).astype(np.float64)
    n = a.shape[0]
    b = 40
    band = np.concatenate([a[:b].reshape(-1, 3), a[-b:].reshape(-1, 3), a[:, :b].reshape(-1, 3), a[:, -b:].reshape(-1, 3)])
    honey = band.mean(0)

    dist = np.abs(a - honey).max(axis=2)
    bgish = dist < BG_THRESH
    reached = np.zeros(bgish.shape, dtype=bool)
    q = deque()
    for sy, sx in [(0, 0), (0, n - 1), (n - 1, 0), (n - 1, n - 1)]:
        if bgish[sy, sx]:
            reached[sy, sx] = True
            q.append((sy, sx))
    if not q:
        sys.exit('No honey corner to seed the flood fill from: is this the master?')
    while q:
        y, x = q.popleft()
        for yy, xx in ((y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1)):
            if 0 <= yy < n and 0 <= xx < n and bgish[yy, xx] and not reached[yy, xx]:
                reached[yy, xx] = True
                q.append((yy, xx))
    face = ~reached
    frac = face.mean()
    print('  face mask: %.1f%% of the master' % (100 * frac))
    if not 0.30 < frac < 0.80:
        sys.exit('Face mask looks wrong (%.1f%% of the image): segmentation failed, not writing' % (100 * frac))

    # Soft matte on the outer fringe only: within ~4px of the flood boundary, alpha follows the colour
    # distance from honey; inside the face it is 1, outside 0.
    hard = Image.fromarray((face * 255).astype(np.uint8))
    near = np.asarray(hard.filter(ImageFilter.MaxFilter(9))) > 0
    core = np.asarray(hard.filter(ImageFilter.MinFilter(9))) > 0
    fringe = near & ~core
    alpha = face.astype(np.float64)
    alpha[fringe] = np.clip(dist[fringe] / 60.0, 0, 1)
    alpha[core] = 1.0
    # Un-mix the honey: colour = (pixel - (1 - alpha) * honey) / alpha, where alpha is meaningful.
    al = alpha[:, :, None]
    rgb = np.where(al > 0.04, (a - (1 - al) * honey) / np.maximum(al, 1e-6), a)
    rgb = np.clip(rgb, 0, 255)
    rgba = np.dstack([rgb, alpha * 255]).astype(np.uint8)
    ys, xs = np.nonzero(alpha > 0.01)
    pad = 4
    box = (max(0, xs.min() - pad), max(0, ys.min() - pad), min(n, xs.max() + 1 + pad), min(n, ys.max() + 1 + pad))
    out = Image.fromarray(rgba).crop(box)
    print('  face bbox: %dx%d' % out.size)
    return out


def compose(face, w, h):
    target = int(min(w, h) * FACE_FRAC)
    scale = target / max(face.size)
    f = face.resize((max(1, round(face.width * scale)), max(1, round(face.height * scale))), Image.LANCZOS)
    canvas = Image.new('RGB', (w, h), CREAM)
    canvas.paste(f, ((w - f.width) // 2, int(h * CENTRE_Y) - f.height // 2), f)
    return canvas


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', help='write under this folder instead of the tree')
    a = ap.parse_args()
    base = a.out or ROOT
    face = cut_face()

    ios = compose(face, CANVAS, CANVAS)
    if a.out or os.path.isdir(os.path.join(ROOT, 'ios')):
        d = os.path.join(base, IOS_DIR)
        os.makedirs(d, exist_ok=True)
        for name in IOS_NAMES:
            ios.save(os.path.join(d, name), 'PNG', optimize=True)
        print('  wrote %s/{%s}  (%dx%d, flat RGB, no alpha)' % (os.path.join(base, IOS_DIR), ','.join(IOS_NAMES), CANVAS, CANVAS))
    else:
        print('  (no ios/ here: run `npx cap add ios` first, or use --out)')

    if a.out or os.path.isdir(os.path.join(ROOT, 'android')):
        for folder, w, h in ANDROID:
            d = os.path.join(base, ANDROID_RES, folder)
            os.makedirs(d, exist_ok=True)
            compose(face, w, h).save(os.path.join(d, 'splash.png'), 'PNG', optimize=True)
        print('  wrote %d Android splash drawables under %s' % (len(ANDROID), os.path.join(base, ANDROID_RES)))


if __name__ == '__main__':
    main()
