#!/usr/bin/env python3
"""Build the native launch splash: the painted Cubby face, centred on Cubby cream.

WHY THIS EXISTS
`npx cap add ios` ships Capacitor's own splash (a blue X on white) in Splash.imageset, and builds 1-5
carried it: every launch flashed Capacitor branding before the cream app appeared. The splash should be
the bear on Cubby cream (#F7F2E8), matching `ios.backgroundColor` and the app's own background so launch
reads as one continuous surface.

The source is the founder's master, icons/icon-master-1024.png: since 2026-11-14 the W2+ teddy on a
light cream-honey watercolour wash (before it, 2026-11-13, a white cub on flat honey), the same image every
icon is made from (tools/gen_brand_icons.py). Until 2026-11-13 this script flood-filled the FLAT
Pillow-drawn face out of icons/logo-512.png; that face is gone everywhere.

A splash is not an icon: we want the face alone on flat cream, not a pasted-on watercolour tile (its edge
would draw a visible square against #F7F2E8). So:
  1. The bear is cut from its wash by gen_brand_icons.analyse(), the same cut the maskable and Android
     icons use: a flood fill from the border through wash-pale pixels (so the enclosed cream muzzle, eyes
     and pink ears stay in), the wash rebuilt under the bear from around it, and a soft matte on the
     outer 14px pulled by colour, so the wash pockets between the fur strokes drop out.
  2. On cream, each fringe pixel keeps its fur and swaps its share of the LOCAL wash for cream
     (pixel + (1 - alpha) x (cream - wash)), so the fur's edge carries no yellow halo. A pale fringe pixel
     with no stroke within 2px (a wash pocket the matte half-kept, which showed as a faint speck beside
     the ear) becomes cream. Checked zoomed at full size at the ear and the head tuft, on cream.
  3. Lanczos-resize so the face's long side is ~22% of the canvas, well inside what survives
     aspect-fill cropping on every device, at the optical centre (46% height); flat RGB.

`ios/` and `android/` are gitignored and regenerated by `npx cap add`, so the output is NOT durable:
re-run after any regen (tools/cap_ios_build.sh does). All three iOS imageset scales get the same 2732
universal image, which is what Capacitor's stock Contents.json expects. With an android/ folder present
the Android splash drawables get the same face at each density and orientation.

Usage: python3 tools/gen_splash.py                 write into ios/ (and android/) of this tree
       python3 tools/gen_splash.py --out DIR       write the same tree under DIR instead
"""
import argparse
import os
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_brand_icons as brand  # noqa: E402  the one cut of the bear from its wash

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MASTER = os.path.join(ROOT, 'icons', 'icon-master-1024.png')
IOS_DIR = os.path.join('ios', 'App', 'App', 'Assets.xcassets', 'Splash.imageset')
IOS_NAMES = ['splash-2732x2732.png', 'splash-2732x2732-1.png', 'splash-2732x2732-2.png']
ANDROID_RES = os.path.join('android', 'app', 'src', 'main', 'res')
ANDROID = [('drawable', 480, 320)] + [
    ('drawable-%s-%s' % (o, d), *(wh if o == 'port' else wh[::-1]))
    for o in ('port', 'land')
    for d, wh in (('mdpi', (320, 480)), ('hdpi', (480, 800)), ('xhdpi', (720, 1280)), ('xxhdpi', (960, 1600)), ('xxxhdpi', (1280, 1920)))
]
CANVAS = 2732
CREAM = (0xF7, 0xF2, 0xE8)
FACE_FRAC = 0.22      # face long side as a fraction of the canvas's short side
CENTRE_Y = 0.46       # optical centre, slightly above geometric


def cut_face():
    """The bear on cream at the master's full size, cropped to it (RGB: everything around it is cream)."""
    if not os.path.exists(MASTER):
        sys.exit('No master at %s' % MASTER)
    master = brand.load_master()
    p = brand.analyse(master)
    print('  bear mask: %.1f%% of the master' % (100 * p['frac']))
    ys, xs = np.nonzero(p['alpha'] > 0)
    n = master.size[0]
    pad = 8
    box = (max(0, xs.min() - pad), max(0, ys.min() - pad), min(n, xs.max() + 1 + pad), min(n, ys.max() + 1 + pad))
    out = brand.on_ground(master, CREAM).crop(box)
    print('  face bbox: %dx%d' % out.size)
    return out


def compose(face, w, h):
    target = int(min(w, h) * FACE_FRAC)
    scale = target / max(face.size)
    f = face.resize((max(1, round(face.width * scale)), max(1, round(face.height * scale))), Image.LANCZOS)
    canvas = Image.new('RGB', (w, h), CREAM)
    canvas.paste(f, ((w - f.width) // 2, int(h * CENTRE_Y) - f.height // 2))
    return canvas


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', help='write under this folder instead of the tree')
    a = ap.parse_args()
    base = a.out or ROOT
    face = cut_face()

    ios = compose(face, CANVAS, CANVAS)
    if a.out or os.path.isdir(os.path.join(ROOT, 'ios')):
        d = os.path.join(base, IOS_DIR)
        os.makedirs(d, exist_ok=True)
        for name in IOS_NAMES:
            ios.save(os.path.join(d, name), 'PNG', optimize=True)
        print('  wrote %s/{%s}  (%dx%d, flat RGB, no alpha)' % (os.path.join(base, IOS_DIR), ','.join(IOS_NAMES), CANVAS, CANVAS))
    else:
        print('  (no ios/ here: run `npx cap add ios` first, or use --out)')

    if a.out or os.path.isdir(os.path.join(ROOT, 'android')):
        for folder, w, h in ANDROID:
            d = os.path.join(base, ANDROID_RES, folder)
            os.makedirs(d, exist_ok=True)
            compose(face, w, h).save(os.path.join(d, 'splash.png'), 'PNG', optimize=True)
        print('  wrote %d Android splash drawables under %s' % (len(ANDROID), os.path.join(base, ANDROID_RES)))


if __name__ == '__main__':
    main()
