#!/usr/bin/env python3
"""Write the iOS AppIcon set from the painted master. Kept under this name because
tools/cap_ios_build.sh calls it on every build.

WHY THIS EXISTS
`npx cap add ios` ships a placeholder AppIcon (Capacitor's blue X). TestFlight build 1+2 carried it.
Apple requires a 1024x1024 marketing icon that is SQUARE and OPAQUE: no alpha channel, no pre-rounded
corners (iOS applies its own squircle mask; a pre-rounded icon gets double-rounded and shows dark
slivers, and an alpha channel is an outright rejection).

Until 2026-11-13 this upscaled the flat Pillow-drawn face in icons/logo-512.png to 1024 and rebuilt its
cream gradient by a surface fit. The icon is now the founder's painted master, icons/icon-master-1024.png
(since 2026-11-15 the deep-brown teddy on a watercolour wash), which is already 1024, square and opaque, so nothing is reconstructed: tools/gen_brand_icons.py resizes
it to every AppIcon size (and the 1024 is the master itself, flattened to RGB) and writes a Contents.json
that lists them all. Since 2026-11-15 each is framed as tools/brand-images.json's "frame" says, drawn along the
iOS corner with the square's corners rim too, so the system's own mask finds rim and never leaves a double
edge (tools/brand_style.py).

`ios/` is gitignored and regenerated by `npx cap add ios`, so the generated icon is NOT durable:
re-run this after any regen. See docs/plans/2026-07-15-native-wrapper-app-store.md

Usage: python3 tools/gen_app_icon.py              into ios/ of this tree
       python3 tools/gen_app_icon.py --out DIR    under DIR instead
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_brand_icons as brand  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument('--out')
a = ap.parse_args()

master = brand.load_master()
files = {k: v for k, v in brand.native_set(master, brand.load_frame()).items() if k.startswith('ios/')}
if not a.out and not os.path.isdir(os.path.join(brand.ROOT, 'ios')):
    sys.exit('No ios/ here: run `npx cap add ios` first, or pass --out DIR')
# The 1024 App Store icon is written as AppIcon-512@2x.png, the name `npx cap add ios` and the old script
# used, so this overwrites it in place: no orphan file, no actool "unassigned child" warning, nothing deleted.
brand.write(files, a.out or brand.ROOT)
print('  mode=RGB everywhere (Apple requires no alpha)')
